//! `cargo xtask goldens fetch|update`: the golden images of the rendering regression suite
//! (M1 task 20).
//!
//! The goldens are renderings of ~40 corpus documents (`tests/corpus/golden-manifest.toml`), the
//! first two pages of each at 96 dpi. They are not kept in the repository: they are one file, a
//! *bundle*, attached to a GitHub release, and `tests/goldens/manifest.toml` names the release and
//! pins the bundle by SHA-256. `fetch` downloads it, checks the hash and unpacks the PNG files into
//! `tests/golden-data/` (git-ignored). `update` renders them again with the engine and writes a new
//! bundle and manifest; after a reviewed PDFium bump, run it, upload the bundle (the command is
//! printed) and commit the manifest.
//!
//! The bundle is a plain sequence of files: the magic `VGOLD1\n`, then for each file a `u32`
//! little-endian name length, the name, a `u64` little-endian length and the bytes. Names are
//! `<id>.p<N>.png` and `ATTRIBUTION.txt` (the source, URL and license of every document, because the
//! images are renderings of other people's work).

use std::fmt::Write as _;
use std::fs::{self, File};
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde::Deserialize;

use crate::Result;
use crate::corpus::{curl_download, sha256_hex};
use crate::manifest::Manifest;

const MAGIC: &[u8] = b"VGOLD1\n";
/// The most the bundle may hold (guards `unpack` against a hostile or corrupt file).
const MAX_BUNDLE_BYTES: u64 = 512 * 1024 * 1024;
const MAX_NAME_BYTES: usize = 200;
const ATTRIBUTION: &str = "ATTRIBUTION.txt";
/// Rendering resolution of every golden.
pub(crate) const DPI: u32 = 96;
/// Pages rendered per document.
const PAGES: u32 = 2;

/// `tests/goldens/manifest.toml`: generated by `update`, read by `fetch` and by the suite.
#[derive(Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub(crate) struct GoldenManifest {
    pub(crate) dpi: u32,
    /// `owner/name` of the repository whose release holds the bundle.
    pub(crate) repo: String,
    pub(crate) tag: String,
    pub(crate) asset: String,
    pub(crate) sha256: String,
    pub(crate) bytes: u64,
    pub(crate) doc: Vec<GoldenDoc>,
}

/// One document: how many of its first pages have a golden.
#[derive(Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub(crate) struct GoldenDoc {
    pub(crate) id: String,
    pub(crate) pages: u32,
}

impl GoldenManifest {
    pub(crate) fn parse(text: &str) -> Result<Self> {
        let manifest: Self = toml::from_str(text)?;
        manifest.validate()?;
        Ok(manifest)
    }

    fn validate(&self) -> Result<()> {
        let hash_ok = self.sha256.len() == 64
            && self
                .sha256
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
        if !hash_ok {
            return Err("sha256 must be 64 lower-case hex digits".into());
        }
        let name_ok = |s: &str| {
            !s.is_empty()
                && s.bytes()
                    .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'-' | b'_'))
        };
        if !name_ok(&self.tag) || !name_ok(&self.asset) {
            return Err("tag and asset use [A-Za-z0-9._-] only".into());
        }
        if self.repo.split('/').count() != 2 || !self.repo.split('/').all(name_ok) {
            return Err("repo is owner/name".into());
        }
        for doc in &self.doc {
            if !name_ok(&doc.id) || !(1..=PAGES).contains(&doc.pages) {
                return Err(format!("bad entry {}", doc.id).into());
            }
        }
        Ok(())
    }

    /// The file names of the goldens, in order.
    pub(crate) fn files(&self) -> Vec<String> {
        self.doc
            .iter()
            .flat_map(|doc| (1..=doc.pages).map(move |page| golden_name(&doc.id, page)))
            .collect()
    }

    /// The manifest as the text `update` writes.
    fn render(&self) -> String {
        let mut out = String::from(
            "# Generated by `cargo xtask goldens update`; do not edit by hand.\n\
             # The golden images of the rendering regression suite (M1 task 20): see docs/dev/testing.md.\n\
             # The bundle is an asset of the release `tag` of `repo`, pinned by `sha256`.\n\n",
        );
        let _ = writeln!(out, "dpi = {}", self.dpi);
        let _ = writeln!(out, "repo = \"{}\"", self.repo);
        let _ = writeln!(out, "tag = \"{}\"", self.tag);
        let _ = writeln!(out, "asset = \"{}\"", self.asset);
        let _ = writeln!(out, "sha256 = \"{}\"", self.sha256);
        let _ = writeln!(out, "bytes = {}", self.bytes);
        for doc in &self.doc {
            let _ = write!(
                out,
                "\n[[doc]]\nid = \"{}\"\npages = {}\n",
                doc.id, doc.pages
            );
        }
        out
    }
}

pub(crate) fn golden_name(id: &str, page: u32) -> String {
    format!("{id}.p{page}.png")
}

// ---- the bundle ------------------------------------------------------------------------------

/// Named files, as a bundle holds them.
type Files = Vec<(String, Vec<u8>)>;

/// Packs named files into a bundle.
pub(crate) fn pack(files: &[(String, Vec<u8>)]) -> Vec<u8> {
    let mut out = MAGIC.to_vec();
    for (name, data) in files {
        out.extend(u32::try_from(name.len()).unwrap_or(u32::MAX).to_le_bytes());
        out.extend(name.as_bytes());
        out.extend(u64::try_from(data.len()).unwrap_or(u64::MAX).to_le_bytes());
        out.extend(data);
    }
    out
}

fn safe_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= MAX_NAME_BYTES
        && !name.starts_with('.')
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'-' | b'_'))
}

/// Unpacks a bundle. Names that could leave the target folder, and lengths that run past the end of
/// the data, are refused.
pub(crate) fn unpack(bytes: &[u8]) -> Result<Vec<(String, Vec<u8>)>> {
    let mut rest = bytes
        .strip_prefix(MAGIC)
        .ok_or("not a golden bundle (bad magic)")?;
    let mut files = Vec::new();
    let take = |rest: &mut &[u8], n: usize| -> Result<Vec<u8>> {
        if rest.len() < n {
            return Err("the bundle is cut short".into());
        }
        let (head, tail) = rest.split_at(n);
        *rest = tail;
        Ok(head.to_vec())
    };
    while !rest.is_empty() {
        let name_len =
            u32::from_le_bytes(take(&mut rest, 4)?.try_into().unwrap_or([0; 4])) as usize;
        if name_len > MAX_NAME_BYTES {
            return Err("a name in the bundle is too long".into());
        }
        let name = String::from_utf8(take(&mut rest, name_len)?)
            .map_err(|_| "a name in the bundle is not text")?;
        if !safe_name(&name) {
            return Err(format!("unsafe name in the bundle: {name:?}").into());
        }
        let len = u64::from_le_bytes(take(&mut rest, 8)?.try_into().unwrap_or([0; 8]));
        let len = usize::try_from(len).map_err(|_| "a file in the bundle is too long")?;
        files.push((name, take(&mut rest, len)?));
    }
    Ok(files)
}

// ---- fetch -----------------------------------------------------------------------------------

pub(crate) fn asset_url(manifest: &GoldenManifest) -> String {
    format!(
        "https://github.com/{}/releases/download/{}/{}",
        manifest.repo, manifest.tag, manifest.asset
    )
}

/// Makes `dir` hold exactly the goldens of the manifest. Returns whether anything was downloaded.
pub(crate) fn fetch(manifest_path: &Path, dir: &Path) -> Result<bool> {
    let text = fs::read_to_string(manifest_path)
        .map_err(|e| format!("cannot read {}: {e}", manifest_path.display()))?;
    let manifest = GoldenManifest::parse(&text)?;
    let stamp = dir.join(".bundle-sha256");
    let current = fs::read_to_string(&stamp).unwrap_or_default();
    let complete = manifest.files().iter().all(|name| dir.join(name).is_file());
    if current.trim() == manifest.sha256 && complete {
        println!(
            "goldens: {} files, already verified",
            manifest.files().len()
        );
        return Ok(false);
    }
    fs::create_dir_all(dir)?;
    let part = dir.join("bundle.part");
    {
        let mut file = File::create(&part)?;
        curl_download(&asset_url(&manifest), &mut file)?;
        file.flush()?;
    }
    let actual = sha256_hex(File::open(&part)?)?;
    if actual != manifest.sha256 {
        let _ = fs::remove_file(&part);
        return Err(format!(
            "sha256 mismatch for {} (expected {}, got {actual})",
            manifest.asset, manifest.sha256
        )
        .into());
    }
    let bytes = fs::read(&part)?;
    let files = unpack(&bytes)?;
    for old in fs::read_dir(dir)? {
        let path = old?.path();
        if path.extension().is_some_and(|e| e == "png" || e == "txt") {
            fs::remove_file(path)?;
        }
    }
    for (name, data) in &files {
        fs::write(dir.join(name), data)?;
    }
    fs::write(&stamp, &manifest.sha256)?;
    fs::remove_file(&part)?;
    let missing: Vec<String> = manifest
        .files()
        .into_iter()
        .filter(|name| !dir.join(name).is_file())
        .collect();
    if !missing.is_empty() {
        return Err(format!("the bundle lacks {missing:?}").into());
    }
    println!(
        "goldens: {} files unpacked from {}",
        files.len(),
        manifest.asset
    );
    Ok(true)
}

// ---- update ----------------------------------------------------------------------------------

fn pdfium_library(root: &Path) -> PathBuf {
    let (platform, file) = match (std::env::consts::OS, std::env::consts::ARCH) {
        ("windows", _) => ("win-x64", "bin/pdfium.dll"),
        ("macos", "aarch64") => ("mac-arm64", "lib/libpdfium.dylib"),
        ("macos", _) => ("mac-x64", "lib/libpdfium.dylib"),
        _ => ("linux-x64", "lib/libpdfium.so"),
    };
    root.join("third_party/pdfium").join(platform).join(file)
}

fn run(command: &mut Command, what: &str) -> Result<String> {
    let output = command
        .output()
        .map_err(|e| format!("cannot run {what}: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "{what} failed ({}): {}",
            output.status,
            String::from_utf8_lossy(&output.stderr).trim()
        )
        .into());
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

/// The number after `"pages":` in the JSON `vellora inspect --json` prints.
fn page_count(json: &str) -> Option<u32> {
    let after = json.split("\"pages\":").nth(1)?;
    let digits: String = after
        .trim_start()
        .chars()
        .take_while(char::is_ascii_digit)
        .collect();
    digits.parse().ok()
}

/// The tag after `current` (`goldens-v3` -> `goldens-v4`).
pub(crate) fn next_tag(current: &str) -> String {
    let (stem, number) = current.rsplit_once("-v").unwrap_or((current, "0"));
    format!("{stem}-v{}", number.parse::<u32>().unwrap_or(0) + 1)
}

/// The text of the attribution file: every source of a rendering, with its license.
fn attribution(corpus: &Manifest) -> String {
    let mut out = String::from(
        "These images are renderings (96 dpi, the first pages) of documents from other projects'\n\
         test collections, made by Vellora's test suite to check that its rendering does not change.\n\
         Each is listed with its source and license. Credit goes to the authors of the documents; the\n\
         renderings are made available under the license of the document they show.\n\n",
    );
    for doc in &corpus.doc {
        let _ = writeln!(
            out,
            "{}\n  source:  {}\n  license: {}\n",
            doc.id, doc.url, doc.license
        );
    }
    out
}

/// Renders the first pages of every document of the subset with the CLI (the way the suite does).
fn render_all(
    root: &Path,
    cli: &Path,
    pdfium: &Path,
    corpus: &Manifest,
) -> Result<(Files, Vec<GoldenDoc>)> {
    let scratch = std::env::temp_dir().join(format!("vellora-goldens-{}", std::process::id()));
    let _ = fs::remove_dir_all(&scratch);
    fs::create_dir_all(&scratch)?;
    let mut files = Vec::new();
    let mut docs = Vec::new();
    for doc in &corpus.doc {
        let pdf = root
            .join("tests/corpus-data")
            .join(format!("{}.pdf", doc.id));
        if !pdf.is_file() {
            return Err(format!(
                "{} is missing: run `cargo xtask corpus fetch --manifest tests/corpus/golden-manifest.toml`",
                pdf.display()
            )
            .into());
        }
        let json = run(
            Command::new(cli).arg("inspect").arg(&pdf).arg("--json"),
            "vellora inspect",
        )?;
        let pages = page_count(&json)
            .ok_or_else(|| format!("{}: no page count in the report", doc.id))?
            .min(PAGES);
        let out = scratch.join(&doc.id);
        let listed = run(
            Command::new(cli)
                .env("VELLORA_PDFIUM_LIB", pdfium)
                .arg("render")
                .arg(&pdf)
                .args([
                    "--pages",
                    &format!("1-{pages}"),
                    "--dpi",
                    &DPI.to_string(),
                    "-o",
                ])
                .arg(&out),
            &format!("vellora render {}", doc.id),
        )?;
        let written: Vec<&str> = listed.lines().collect();
        if written.len() != pages as usize {
            return Err(format!("{}: {} files for {pages} pages", doc.id, written.len()).into());
        }
        for (page, path) in (1..).zip(&written) {
            files.push((golden_name(&doc.id, page), fs::read(path)?));
        }
        docs.push(GoldenDoc {
            id: doc.id.clone(),
            pages,
        });
        println!("rendered {} ({pages} page(s))", doc.id);
    }
    let _ = fs::remove_dir_all(&scratch);
    Ok((files, docs))
}

/// Renders every document again and writes the bundle and the manifest. `tag` is the release the
/// bundle will be attached to (the next one after the current if `None`).
pub(crate) fn update(root: &Path, tag: Option<&str>) -> Result<()> {
    let corpus_path = root.join("tests/corpus/golden-manifest.toml");
    let corpus = Manifest::parse(&fs::read_to_string(&corpus_path)?)?;
    let manifest_path = root.join("tests/goldens/manifest.toml");
    let old = fs::read_to_string(&manifest_path)
        .ok()
        .and_then(|text| GoldenManifest::parse(&text).ok());
    let repo = old
        .as_ref()
        .map_or_else(|| "jhjh1214/vellora".to_owned(), |m| m.repo.clone());
    let tag = tag.map_or_else(
        || {
            old.as_ref()
                .map_or_else(|| "goldens-v1".to_owned(), |m| next_tag(&m.tag))
        },
        str::to_owned,
    );

    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    run(
        Command::new(&cargo)
            .args([
                "build",
                "--locked",
                "-p",
                "vellora-cli",
                "-p",
                "vellora-engine",
            ])
            .current_dir(root),
        "cargo build",
    )?;
    let cli = root
        .join("target/debug")
        .join(format!("vellora{}", std::env::consts::EXE_SUFFIX));
    let pdfium =
        std::env::var_os("VELLORA_PDFIUM_LIB").map_or_else(|| pdfium_library(root), PathBuf::from);
    if !pdfium.is_file() {
        return Err(format!(
            "PDFium not found at {}: run `cargo xtask pdfium fetch`",
            pdfium.display()
        )
        .into());
    }

    let (mut files, docs) = render_all(root, &cli, &pdfium, &corpus)?;
    files.push((ATTRIBUTION.to_owned(), attribution(&corpus).into_bytes()));

    let bundle = pack(&files);
    if bundle.len() as u64 > MAX_BUNDLE_BYTES {
        return Err("the bundle is too large".into());
    }
    let asset = format!("{tag}.bundle");
    let out_dir = root.join("target/goldens");
    fs::create_dir_all(&out_dir)?;
    let bundle_path = out_dir.join(&asset);
    fs::write(&bundle_path, &bundle)?;
    let manifest = GoldenManifest {
        dpi: DPI,
        repo: repo.clone(),
        tag: tag.clone(),
        asset: asset.clone(),
        sha256: sha256_hex(&bundle[..])?,
        bytes: bundle.len() as u64,
        doc: docs,
    };
    if let Some(parent) = manifest_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&manifest_path, manifest.render())?;
    println!(
        "\nwrote {} ({} bytes) and {}\n\nTo publish the goldens (they are renderings of other projects' documents; the bundle\n\
         holds their attribution):\n  gh release create {tag} {} --repo {repo} --prerelease \
         --title \"Rendering goldens {tag}\" --notes \"Golden images of the rendering regression suite. See tests/goldens/manifest.toml and ATTRIBUTION.txt inside the bundle.\"\n\
         then commit tests/goldens/manifest.toml.",
        bundle_path.display(),
        bundle.len(),
        manifest_path.display(),
        bundle_path.display(),
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Vec<(String, Vec<u8>)> {
        vec![
            ("a.p1.png".to_owned(), vec![1, 2, 3]),
            ("b.p1.png".to_owned(), Vec::new()),
            (ATTRIBUTION.to_owned(), b"text".to_vec()),
        ]
    }

    #[test]
    fn a_bundle_unpacks_to_what_was_packed() {
        assert_eq!(unpack(&pack(&sample())).unwrap(), sample());
        assert_eq!(unpack(&pack(&[])).unwrap(), Vec::new());
    }

    #[test]
    fn a_damaged_bundle_is_refused_not_misread() {
        let good = pack(&sample());
        assert!(unpack(b"VGOLD2\nabc").is_err(), "wrong magic");
        assert!(unpack(&good[..good.len() - 1]).is_err(), "cut short");
        assert!(unpack(&good[..MAGIC.len() + 2]).is_err(), "cut in a length");
        // A length that claims more than there is.
        let mut lying = pack(&[("x.png".to_owned(), vec![0; 4])]);
        let at = lying.len() - 4 - 8;
        lying[at..at + 8].copy_from_slice(&u64::MAX.to_le_bytes());
        assert!(unpack(&lying).is_err());
    }

    #[test]
    fn names_that_could_leave_the_folder_are_refused() {
        for bad in [
            "../x.png", "a/b.png", "a\\b.png", ".hidden", "", "C:x.png", "x y.png",
        ] {
            let bundle = pack(&[(bad.to_owned(), vec![1])]);
            assert!(unpack(&bundle).is_err(), "{bad:?} was accepted");
        }
        let long = "a".repeat(MAX_NAME_BYTES + 1);
        assert!(unpack(&pack(&[(long, vec![1])])).is_err());
    }

    #[test]
    fn the_manifest_round_trips_and_is_validated() {
        let m = GoldenManifest {
            dpi: 96,
            repo: "o/r".into(),
            tag: "goldens-v2".into(),
            asset: "goldens-v2.bundle".into(),
            sha256: "0".repeat(64),
            bytes: 10,
            doc: vec![
                GoldenDoc {
                    id: "d-1".into(),
                    pages: 2,
                },
                GoldenDoc {
                    id: "e".into(),
                    pages: 1,
                },
            ],
        };
        assert_eq!(GoldenManifest::parse(&m.render()).unwrap(), m);
        assert_eq!(m.files(), ["d-1.p1.png", "d-1.p2.png", "e.p1.png"]);
        assert_eq!(
            asset_url(&m),
            "https://github.com/o/r/releases/download/goldens-v2/goldens-v2.bundle"
        );
        for broken in [
            m.render().replace(&"0".repeat(64), "XYZ"),
            m.render().replace("o/r", "o"),
            m.render().replace("pages = 2", "pages = 3"),
            m.render().replace("goldens-v2.bundle", "../x"),
            m.render().replace("dpi = 96", "dpi = 96\nsurprise = 1"),
        ] {
            assert!(GoldenManifest::parse(&broken).is_err(), "{broken}");
        }
    }

    #[test]
    fn the_next_tag_counts_on() {
        assert_eq!(next_tag("goldens-v1"), "goldens-v2");
        assert_eq!(next_tag("goldens-v9"), "goldens-v10");
        assert_eq!(next_tag("odd"), "odd-v1");
    }

    #[test]
    fn the_page_count_is_read_from_the_report() {
        assert_eq!(page_count("{\n  \"pages\": 12,\n  \"x\": 1\n}"), Some(12));
        assert_eq!(page_count("{\"pages\": null}"), None);
        assert_eq!(page_count("{}"), None);
    }

    /// The committed manifest names exactly the documents of the corpus subset, 1 or 2 pages each.
    #[test]
    fn the_committed_goldens_manifest_matches_the_corpus_subset() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let Ok(text) = fs::read_to_string(root.join("tests/goldens/manifest.toml")) else {
            return; // not generated yet
        };
        let goldens = GoldenManifest::parse(&text).unwrap();
        let corpus = Manifest::parse(
            &fs::read_to_string(root.join("tests/corpus/golden-manifest.toml")).unwrap(),
        )
        .unwrap();
        let ids: Vec<&str> = corpus.doc.iter().map(|d| d.id.as_str()).collect();
        let named: Vec<&str> = goldens.doc.iter().map(|d| d.id.as_str()).collect();
        assert_eq!(named, ids);
        assert_eq!(goldens.dpi, DPI);
    }
}
