#include "commands/ShortcutsPage.h"

#include <QStringList>

namespace vellora {

namespace {

// Headings of the groups; a group with another prefix gets the prefix, capitalised.
QString groupTitle(const QString& prefix) {
    if (prefix == QLatin1String("file")) {
        return QStringLiteral("File");
    }
    if (prefix == QLatin1String("tabs")) {
        return QStringLiteral("Tabs");
    }
    if (prefix == QLatin1String("edit")) {
        return QStringLiteral("Edit");
    }
    if (prefix == QLatin1String("view")) {
        return QStringLiteral("View");
    }
    if (prefix == QLatin1String("help")) {
        return QStringLiteral("Help");
    }
    if (prefix == QLatin1String("palette")) {
        return QStringLiteral("Command palette");
    }
    return prefix.left(1).toUpper() + prefix.mid(1);
}

QString groupOf(const Command& command) {
    return command.id.section(QLatin1Char('.'), 0, 0);
}

} // namespace

QString shortcutsMarkdown(const CommandRegistry& registry) {
    QString text;
    text += QStringLiteral("# Keyboard shortcuts\n\n");
    text += QStringLiteral(
        "<!-- Generated by `vellora --export-shortcuts` from the command registry. Do not edit "
        "by hand: CI regenerates this page and fails if it differs. -->\n\n");
    text += QStringLiteral(
        "Every action of Vellora is a command with a name, listed here with its shortcut. Any "
        "command, with or without a shortcut, can be run from the command palette "
        "(`Ctrl+Shift+P`): type part of its name and press Enter.\n\n");
    text += QStringLiteral(
        "On macOS, Ctrl means the Command key. Shortcuts for standard actions (Open, Print, "
        "Close Tab, Quit, Copy, Select All, Find, Zoom In, Zoom Out) follow the conventions of "
        "your system, so they can differ from the keys shown here.\n");

    QStringList groups;
    for (const Command& command : registry.commands()) {
        if (!command.shortcuts.isEmpty() && !groups.contains(groupOf(command))) {
            groups.append(groupOf(command));
        }
    }
    for (const QString& group : groups) {
        text +=
            QStringLiteral("\n## %1\n\n| Command | Shortcut |\n|---|---|\n").arg(groupTitle(group));
        for (const Command& command : registry.commands()) {
            if (command.shortcuts.isEmpty() || groupOf(command) != group) {
                continue;
            }
            QStringList keys;
            for (const QKeySequence& sequence : command.shortcuts) {
                keys.append(
                    QStringLiteral("`%1`").arg(sequence.toString(QKeySequence::PortableText)));
            }
            text +=
                QStringLiteral("| %1 | %2 |\n").arg(command.title, keys.join(QStringLiteral(", ")));
        }
    }
    return text;
}

} // namespace vellora
